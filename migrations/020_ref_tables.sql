CREATE TABLE $(NS).country (
    country_code citext NOT NULL CONSTRAINT pk_country PRIMARY KEY
    CONSTRAINT ck_country_code_len CHECK (char_length(country_code) = 2),
    country_name varchar(100) NOT NULL,
    currency_code citext NOT NULL CONSTRAINT ck_country_currency_len CHECK (char_length(currency_code) = 3),
    is_eu_member boolean NOT NULL CONSTRAINT df_country_eu DEFAULT true,
    premium_tax_rate numeric(5, 4) NOT NULL
);

CREATE TABLE $(NS).product (
    product_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_product PRIMARY KEY,
    product_code citext NOT NULL CONSTRAINT uq_product_code UNIQUE
    CONSTRAINT ck_product_code_len CHECK (char_length(product_code) <= 20),
    product_name varchar(100) NOT NULL,
    line_of_business citext NOT NULL,
    base_rate numeric(9, 6) NOT NULL,
    min_premium numeric(19, 4) NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);
