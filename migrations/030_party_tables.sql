CREATE TABLE $(NS).broker (
    broker_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_broker PRIMARY KEY,
    broker_code citext NOT NULL CONSTRAINT uq_broker_code UNIQUE
    CONSTRAINT ck_broker_code_len CHECK (char_length(broker_code) <= 20),
    broker_name varchar(200) NOT NULL,
    country_code citext NOT NULL CONSTRAINT fk_broker_country REFERENCES $(NS).country (country_code),
    commission_pct numeric(5, 2) NOT NULL,
    email citext,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE $(NS).policyholder (
    policyholder_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_policyholder PRIMARY KEY,
    external_ref uuid NOT NULL DEFAULT gen_random_uuid() CONSTRAINT uq_policyholder_ref UNIQUE,
    first_name citext NOT NULL,
    middle_name citext,
    last_name citext NOT NULL,
    full_name text GENERATED ALWAYS AS (first_name::text || ' ' || last_name::text) STORED,
    date_of_birth date NOT NULL,
    email citext,
    phone varchar(30),
    iban varchar(34) NOT NULL,
    address_line varchar(200) NOT NULL,
    postcode varchar(12) NOT NULL,
    city varchar(100) NOT NULL,
    country_code citext NOT NULL CONSTRAINT fk_policyholder_country REFERENCES $(NS).country (country_code),
    created_at timestamptz(3) NOT NULL DEFAULT now()
);
CREATE INDEX ix_policyholder_last_name ON $(NS).policyholder (last_name, first_name);
CREATE INDEX ix_policyholder_email ON $(NS).policyholder (email) WHERE email IS NOT NULL;
