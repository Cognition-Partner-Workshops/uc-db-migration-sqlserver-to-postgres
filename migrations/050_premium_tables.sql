CREATE TABLE $(NS).premium_schedule (
    schedule_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_premium_schedule PRIMARY KEY,
    policy_id integer NOT NULL CONSTRAINT fk_schedule_policy REFERENCES $(NS).policy (policy_id),
    installment_no smallint NOT NULL CONSTRAINT ck_schedule_installment CHECK (installment_no BETWEEN 0 AND 255),
    due_date date NOT NULL,
    amount_due numeric(19, 4) NOT NULL,
    paid_amount numeric(19, 4) NOT NULL DEFAULT 0,
    status citext NOT NULL CONSTRAINT ck_schedule_status CHECK (status IN ('DUE', 'PAID', 'OVERDUE', 'CANCELLED')),
    CONSTRAINT uq_schedule_installment UNIQUE (policy_id, installment_no)
);
-- filtered index -> partial index
CREATE INDEX ix_premium_schedule_open ON $(NS).premium_schedule (due_date)
INCLUDE (policy_id, amount_due, paid_amount)
WHERE status IN ('DUE', 'OVERDUE');

CREATE TABLE $(NS).premium_payment (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_premium_payment PRIMARY KEY,
    payment_ref uuid NOT NULL DEFAULT gen_random_uuid() CONSTRAINT uq_payment_ref UNIQUE,
    policy_id integer NOT NULL CONSTRAINT fk_payment_policy REFERENCES $(NS).policy (policy_id),
    schedule_id integer CONSTRAINT fk_payment_schedule REFERENCES $(NS).premium_schedule (schedule_id),
    paid_at timestamptz(3) NOT NULL,
    amount numeric(19, 4) NOT NULL,
    method citext NOT NULL CONSTRAINT ck_payment_method CHECK (method IN ('SEPA_DD', 'CARD', 'TRANSFER')),
    payer_iban varchar(34),
    reference_text varchar(140)
);
CREATE INDEX ix_premium_payment_policy ON $(NS).premium_payment (policy_id, paid_at);
