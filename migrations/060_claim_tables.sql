CREATE TABLE $(NS).claim (
    claim_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_claim PRIMARY KEY,
    claim_number citext NOT NULL CONSTRAINT uq_claim_number UNIQUE,
    policy_id integer NOT NULL CONSTRAINT fk_claim_policy REFERENCES $(NS).policy (policy_id),
    loss_date date NOT NULL,
    reported_at timestamp(0) NOT NULL,
    cause_code citext,
    status citext NOT NULL CONSTRAINT ck_claim_status CHECK (status IN ('OPEN', 'CLOSED', 'REOPENED', 'DENIED')),
    description varchar(400),
    closed_at timestamp(0)
);
-- ROWVERSION is not carried over: optimistic concurrency uses the xmin system column.
CREATE INDEX ix_claim_policy ON $(NS).claim (policy_id, loss_date);

CREATE TABLE $(NS).claim_reserve (
    reserve_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_claim_reserve PRIMARY KEY,
    claim_id integer NOT NULL CONSTRAINT fk_reserve_claim REFERENCES $(NS).claim (claim_id),
    reserve_type citext NOT NULL CONSTRAINT ck_reserve_type CHECK (reserve_type IN ('INDEMNITY', 'EXPENSE')),
    amount numeric(19, 4) NOT NULL,
    set_at timestamp(3) NOT NULL,
    set_by varchar(50) NOT NULL,
    CONSTRAINT uq_claim_reserve UNIQUE (claim_id, reserve_type)
);

CREATE TABLE $(NS).claim_payment (
    claim_payment_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_claim_payment PRIMARY KEY,
    claim_id integer NOT NULL CONSTRAINT fk_claim_payment_claim REFERENCES $(NS).claim (claim_id),
    reserve_type citext NOT NULL,
    paid_at timestamp(3) NOT NULL,
    amount numeric(19, 4) NOT NULL,
    payee_name varchar(200) NOT NULL,
    payee_iban varchar(34)
);
CREATE INDEX ix_claim_payment_claim ON $(NS).claim_payment (claim_id, reserve_type);
