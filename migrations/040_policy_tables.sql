CREATE TABLE $(NS).policy (
    policy_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_policy PRIMARY KEY,
    policy_number citext NOT NULL
    DEFAULT ('P' || lpad(nextval('$(NS).seq_policy_number')::text, 9, '0'))
    CONSTRAINT uq_policy_number UNIQUE,
    policyholder_id integer NOT NULL CONSTRAINT fk_policy_holder REFERENCES $(NS).policyholder (policyholder_id),
    broker_id integer CONSTRAINT fk_policy_broker REFERENCES $(NS).broker (broker_id),
    product_id integer NOT NULL CONSTRAINT fk_policy_product REFERENCES $(NS).product (product_id),
    status citext NOT NULL
    CONSTRAINT ck_policy_status CHECK (status IN ('QUOTE', 'ACTIVE', 'LAPSED', 'CANCELLED', 'EXPIRED')),
    inception_date date NOT NULL,
    expiry_date date NOT NULL,
    payment_frequency smallint NOT NULL CONSTRAINT ck_policy_frequency CHECK (payment_frequency IN (1, 2, 4, 12)),
    annual_premium numeric(19, 4) NOT NULL,
    currency_code citext NOT NULL DEFAULT 'EUR',
    created_at timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at timestamp(3)
);
CREATE INDEX ix_policy_holder ON $(NS).policy (policyholder_id);
CREATE INDEX ix_policy_broker ON $(NS).policy (broker_id) INCLUDE (annual_premium, status);

CREATE TABLE $(NS).policy_version (
    policy_version_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_policy_version PRIMARY KEY,
    policy_id integer NOT NULL CONSTRAINT fk_version_policy REFERENCES $(NS).policy (policy_id),
    version_no integer NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    sum_insured numeric(19, 4) NOT NULL,
    annual_premium numeric(19, 4) NOT NULL,
    change_reason varchar(200),
    created_at timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT uq_policy_version UNIQUE (policy_id, version_no)
);
-- SQL Server clustered index -> ordinary b-tree; PostgreSQL has no clustered
-- storage order, so "current version" queries must ORDER BY explicitly.
CREATE INDEX cx_policy_version_latest ON $(NS).policy_version (policy_id, effective_from DESC, version_no DESC);

CREATE TABLE $(NS).coverage (
    coverage_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_coverage PRIMARY KEY,
    policy_id integer NOT NULL CONSTRAINT fk_coverage_policy REFERENCES $(NS).policy (policy_id),
    coverage_code citext NOT NULL,
    limit_amount numeric(19, 4) NOT NULL,
    deductible numeric(19, 4) NOT NULL DEFAULT 0,
    premium_share numeric(7, 4) NOT NULL
);
CREATE INDEX ix_coverage_policy ON $(NS).coverage (policy_id, coverage_code);
