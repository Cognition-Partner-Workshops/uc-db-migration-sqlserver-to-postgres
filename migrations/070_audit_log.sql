CREATE TABLE $(NS).audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_audit_log PRIMARY KEY,
    table_name varchar(128) NOT NULL,
    action varchar(10) NOT NULL,
    key_value varchar(400) NOT NULL,
    old_value varchar(100),
    new_value varchar(100),
    row_count integer NOT NULL DEFAULT 1,
    changed_at timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    changed_by varchar(128) NOT NULL DEFAULT current_user
);
